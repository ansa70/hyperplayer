import { generateKeyPairSync, randomBytes, sign, X509Certificate } from "node:crypto";
import { mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { isIP } from "node:net";
import { hostname, networkInterfaces } from "node:os";
import { join } from "node:path";
import type { TlsConfig } from "../config.ts";

/** A generated certificate is replaced this long before it expires. */
const RENEW_BEFORE_MS = 30 * 86_400_000;
const VALID_YEARS = 10;

export type Tls = {
  key: string;
  cert: string;
  /** SHA-256 of the certificate, as clients show it when asked to trust a self-signed one. */
  fingerprint: string;
  /** Generated by us (not given): clients need to trust it explicitly. */
  selfSigned: boolean;
  /** For certificates from files: the files' current state, to notice renewals. */
  stamp: string;
};

/** The certificate files' state: changes when they're renewed (e.g. by certbot). */
export function stampOf(files: string[]): string {
  return files.map((f) => statSync(f).mtimeMs).join(":");
}

/** Loads the configured certificate, or the self-signed one in `dataDir` (created or renewed as needed). */
export function loadTls(config: TlsConfig, dataDir: string): Tls {
  if (config.certFile && config.keyFile) {
    const cert = readFileSync(config.certFile, "utf8");
    return {
      key: readFileSync(config.keyFile, "utf8"),
      cert,
      fingerprint: new X509Certificate(cert).fingerprint256,
      selfSigned: false,
      stamp: stampOf([config.certFile, config.keyFile]),
    };
  }
  const dir = join(dataDir, "tls");
  const [certFile, keyFile] = [join(dir, "cert.pem"), join(dir, "key.pem")];
  const wanted = [...new Set(["localhost", hostname(), ...config.names])];
  try {
    const cert = readFileSync(certFile, "utf8");
    const x509 = new X509Certificate(cert);
    if (Date.parse(x509.validTo) - Date.now() > RENEW_BEFORE_MS && wanted.every((n) => covers(x509, n))) {
      return {
        key: readFileSync(keyFile, "utf8"),
        cert,
        fingerprint: x509.fingerprint256,
        selfSigned: true,
        stamp: "",
      };
    }
  } catch {
    // None yet (or unreadable): make one.
  }
  const names = [...new Set([...wanted, "127.0.0.1", "::1", ...interfaceAddresses()])];
  const { key, cert } = selfSigned(names);
  mkdirSync(dir, { recursive: true });
  writeFileSync(keyFile, key, { mode: 0o600 });
  writeFileSync(certFile, cert);
  return { key, cert, fingerprint: new X509Certificate(cert).fingerprint256, selfSigned: true, stamp: "" };
}

/** Whether the certificate names `name` (a host name or IP address). */
function covers(x509: X509Certificate, name: string): boolean {
  return isIP(name) ? x509.checkIP(name) !== undefined : x509.checkHost(name) !== undefined;
}

function interfaceAddresses(): string[] {
  return Object.values(networkInterfaces())
    .flat()
    .filter((a) => a && !a.internal && !a.address.startsWith("fe80:"))
    .map((a) => a!.address);
}

// ------------------------------------------------------- self-signed certificate
//
// Node can't create certificates, so this writes the DER of a minimal one (RFC 5280):
// an ECDSA P-256 key, the given names as subject alternative names, valid 10 years.

function der(tag: number, ...content: Buffer[]): Buffer {
  const body = Buffer.concat(content);
  const n = body.length;
  const length =
    n < 0x80 ? Buffer.from([n]) : n < 0x100 ? Buffer.from([0x81, n]) : Buffer.from([0x82, n >> 8, n & 0xff]);
  return Buffer.concat([Buffer.from([tag]), length, body]);
}

const seq = (...content: Buffer[]) => der(0x30, ...content);

function oid(dotted: string): Buffer {
  const [a, b, ...rest] = dotted.split(".").map(Number);
  const bytes = [40 * a! + b!];
  for (const n of rest) {
    const chunk = [n & 0x7f];
    for (let v = n >> 7; v > 0; v >>= 7) chunk.unshift((v & 0x7f) | 0x80);
    bytes.push(...chunk);
  }
  return der(0x06, Buffer.from(bytes));
}

function time(date: Date): Buffer {
  const iso = date.toISOString().replace(/[-:T]/g, "").slice(0, 14) + "Z"; // YYYYMMDDHHMMSSZ
  return date.getUTCFullYear() < 2050 ? der(0x17, Buffer.from(iso.slice(2))) : der(0x18, Buffer.from(iso));
}

function ipBytes(ip: string): Buffer {
  if (isIP(ip) === 4) return Buffer.from(ip.split(".").map(Number));
  // Expand "::" and write the eight 16-bit groups.
  const [head, tail = ""] = ip.split("::");
  const parts = (s: string) => (s ? s.split(":") : []);
  const groups = [
    ...parts(head!),
    ...Array(8 - parts(head!).length - parts(tail).length).fill("0"),
    ...parts(tail),
  ];
  return Buffer.from(groups.flatMap((g: string) => [parseInt(g, 16) >> 8, parseInt(g, 16) & 0xff]));
}

export function selfSigned(names: string[], now = new Date()): { key: string; cert: string } {
  const { publicKey, privateKey } = generateKeyPairSync("ec", { namedCurve: "P-256" });
  const ecdsaSha256 = seq(oid("1.2.840.10045.4.3.2"));
  const serial = randomBytes(16);
  serial[0] = (serial[0]! & 0x7f) | 0x01; // positive and minimal
  const name = seq(der(0x31, seq(oid("2.5.4.3"), der(0x0c, Buffer.from(`HyperPlayer (${hostname()})`)))));
  const notAfter = new Date(now);
  notAfter.setUTCFullYear(notAfter.getUTCFullYear() + VALID_YEARS);
  const altNames = names.map((n) => (isIP(n) ? der(0x87, ipBytes(n)) : der(0x82, Buffer.from(n))));
  const extension = (id: string, value: Buffer, critical = false) =>
    seq(oid(id), ...(critical ? [der(0x01, Buffer.from([0xff]))] : []), der(0x04, value));
  const extensions = seq(
    extension("2.5.29.17", seq(...altNames)),
    extension("2.5.29.19", seq(), true), // basic constraints: not a CA
    extension("2.5.29.15", der(0x03, Buffer.from([0x07, 0x80])), true), // key usage: digital signature
    extension("2.5.29.37", seq(oid("1.3.6.1.5.5.7.3.1"))), // extended key usage: server auth
  );
  const tbs = seq(
    der(0xa0, der(0x02, Buffer.from([2]))), // version 3
    der(0x02, serial),
    ecdsaSha256,
    name, // issuer: itself
    seq(time(now), time(notAfter)),
    name,
    publicKey.export({ type: "spki", format: "der" }),
    der(0xa3, extensions),
  );
  const signature = sign("sha256", tbs, privateKey);
  const cert = seq(tbs, ecdsaSha256, der(0x03, Buffer.from([0]), signature));
  const pem = (label: string, body: Buffer) =>
    `-----BEGIN ${label}-----\n${body.toString("base64").replace(/.{1,64}/g, "$&\n")}-----END ${label}-----\n`;
  return {
    key: privateKey.export({ type: "pkcs8", format: "pem" }).toString(),
    cert: pem("CERTIFICATE", cert),
  };
}
