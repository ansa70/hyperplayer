//! The player in other languages. The Slint UI translates its own text (`@tr`) from the
//! catalogs bundled in `translations/<lang>/LC_MESSAGES/hyperplayer.po`; text built here in
//! Rust (statuses, subtitles, errors) goes through [`tr!`] and [`trn!`], from the same files.
//!
//! Placeholders follow Slint's: `{}` takes the next argument, `{0}`, `{1}`… a given one
//! (so a translation can reorder them), `{n}` the count of a plural, `{{` and `}}` braces.

use std::{
    collections::HashMap,
    fmt::{Display, Write},
    sync::{
        OnceLock,
        atomic::{AtomicUsize, Ordering},
    },
};

/// A language's messages: (msgid, its translations, one per plural form).
type Entries = &'static [(&'static str, &'static [&'static str])];

// `CATALOGS`: (language, its entries), generated by build.rs from the .po files.
include!(concat!(env!("OUT_DIR"), "/translations.rs"));

/// 0 for English (the text as written), otherwise 1 + an index into `CATALOGS`.
#[cfg(not(test))]
static CURRENT: AtomicUsize = AtomicUsize::new(0);

fn current() -> usize {
    #[cfg(not(test))]
    return CURRENT.load(Ordering::Relaxed);
    #[cfg(test)]
    TEST_CURRENT.with(|c| c.load(Ordering::Relaxed))
}

fn set_current(index: usize) {
    #[cfg(not(test))]
    CURRENT.store(index, Ordering::Relaxed);
    #[cfg(test)]
    TEST_CURRENT.with(|c| c.store(index, Ordering::Relaxed));
}

// Tests run in parallel: each has its own language, so one switching doesn't affect another.
#[cfg(test)]
thread_local! {
    static TEST_CURRENT: AtomicUsize = const { AtomicUsize::new(0) };
}

type Catalog = HashMap<&'static str, &'static [&'static str]>;

fn catalogs() -> &'static [Catalog] {
    static MAPS: OnceLock<Vec<Catalog>> = OnceLock::new();
    MAPS.get_or_init(|| {
        CATALOGS
            .iter()
            .map(|(_, entries)| entries.iter().copied().collect())
            .collect()
    })
}

/// The languages the player speaks, as (code, name in that language), English first.
pub fn languages() -> Vec<(&'static str, &'static str)> {
    std::iter::once(("en", "English"))
        .chain(CATALOGS.iter().map(|(code, _)| (*code, native_name(code))))
        .collect()
}

fn native_name(code: &str) -> &'static str {
    match code {
        "it" => "Italiano",
        _ => "?",
    }
}

/// The language a setting stands for: itself when the player has it, otherwise (or for
/// "", automatic) the system's when it has that, otherwise English.
pub fn resolve(setting: &str) -> &'static str {
    let have = |code: &str| {
        let base = code.split(['-', '_', '.', '@']).next().unwrap_or("");
        languages()
            .into_iter()
            .map(|(c, _)| c)
            .find(|c| c.eq_ignore_ascii_case(base))
    };
    have(setting)
        .or_else(|| sys_locale::get_locales().find_map(|l| have(&l)))
        .unwrap_or("en")
}

/// Switches the text built from now on to `code` (as [`resolve`] returns).
pub fn set_language(code: &str) {
    let index = CATALOGS
        .iter()
        .position(|(c, _)| *c == code)
        .map_or(0, |i| i + 1);
    set_current(index);
}

/// The language in use, as its code.
pub fn language() -> &'static str {
    match current() {
        0 => "en",
        i => CATALOGS[i - 1].0,
    }
}

fn lookup(msgid: &str) -> Option<&'static [&'static str]> {
    match current() {
        0 => None,
        i => catalogs()[i - 1].get(msgid).copied(),
    }
}

/// Text known only at run time (e.g. from the server) in the language in use, if it's in
/// the catalog: listed somewhere with [`msg!`].
pub fn translate(text: &str) -> Option<&'static str> {
    lookup(text).and_then(|s| s.first().copied())
}

/// `msgid` in the language in use.
pub fn tr(msgid: &'static str) -> &'static str {
    lookup(msgid)
        .and_then(|s| s.first().copied())
        .unwrap_or(msgid)
}

/// The singular or plural form for `n`, in the language in use.
pub fn tr_plural(one: &'static str, other: &'static str, n: i64) -> &'static str {
    // Every language bundled so far has English's rule: one form for 1, another otherwise.
    let form = usize::from(n != 1);
    match lookup(one) {
        Some(forms) => forms.get(form).or(forms.first()).copied().unwrap_or(one),
        None if form == 0 => one,
        None => other,
    }
}

/// Fills a template's placeholders (see the module's comment).
pub fn format(template: &str, args: &[&dyn Display], n: Option<i64>) -> String {
    let mut out = String::with_capacity(template.len() + 16);
    let mut next = 0;
    let mut chars = template.char_indices().peekable();
    while let Some((i, c)) = chars.next() {
        match c {
            '{' if chars.peek().is_some_and(|&(_, c)| c == '{') => {
                chars.next();
                out.push('{');
            }
            '}' if chars.peek().is_some_and(|&(_, c)| c == '}') => {
                chars.next();
                out.push('}');
            }
            '{' => {
                let Some(end) = template[i..].find('}') else {
                    out.push_str(&template[i..]);
                    break;
                };
                let key = &template[i + 1..i + end];
                let arg = match key {
                    "" => {
                        next += 1;
                        args.get(next - 1)
                    }
                    "n" if n.is_some() => {
                        let _ = write!(out, "{}", n.unwrap_or_default());
                        None
                    }
                    _ => key.parse::<usize>().ok().and_then(|k| args.get(k)),
                };
                if let Some(arg) = arg {
                    let _ = write!(out, "{arg}");
                } else if !(key == "n" && n.is_some()) {
                    out.push_str(&template[i..=i + end]);
                }
                while chars.peek().is_some_and(|&(j, _)| j <= i + end) {
                    chars.next();
                }
            }
            c => out.push(c),
        }
    }
    out
}

/// `tr!("text")` is the text translated (a `&'static str`); `tr!("{} of {}", a, b)` the
/// translation with the arguments filled in (a `String`).
#[macro_export]
macro_rules! tr {
    ($msgid:literal) => {
        $crate::i18n::tr($msgid)
    };
    ($msgid:literal, $($arg:expr),+ $(,)?) => {
        $crate::i18n::format($crate::i18n::tr($msgid), &[$(&$arg as &dyn ::std::fmt::Display),+], None)
    };
}

/// `msg!("text")` is the text as written: it marks text to put in the catalogs, for
/// [`translate`] to find at run time.
#[macro_export]
macro_rules! msg {
    ($msgid:literal) => {
        $msgid
    };
}

/// `trn!("{n} track", "{n} tracks", n)`: the form for `n`, translated, with `{n}` (and any
/// further arguments, as with [`tr!`]) filled in.
#[macro_export]
macro_rules! trn {
    ($one:literal, $other:literal, $n:expr $(, $arg:expr)* $(,)?) => {{
        let n = $n as i64;
        $crate::i18n::format(
            $crate::i18n::tr_plural($one, $other, n),
            &[$(&$arg as &dyn ::std::fmt::Display),*],
            Some(n),
        )
    }};
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fills_placeholders() {
        assert_eq!(format("{} of {}", &[&1, &"two"], None), "1 of two");
        assert_eq!(format("{1} before {0}", &[&"a", &"b"], None), "b before a");
        assert_eq!(format("{n} tracks, {}", &[&"x"], Some(3)), "3 tracks, x");
        assert_eq!(format("{{literal}} {}", &[&5], None), "{literal} 5");
        assert_eq!(format("missing {}", &[], None), "missing {}");
    }

    #[test]
    fn every_language_has_its_name() {
        for (code, name) in languages() {
            assert_ne!(name, "?", "no name for {code}");
        }
    }

    #[test]
    fn translates_and_falls_back() {
        set_language("it");
        assert_eq!(tr("Settings"), "Impostazioni");
        assert_eq!(
            tr("not a message anyone wrote"),
            "not a message anyone wrote"
        );
        assert_eq!(trn!("{n} track", "{n} tracks", 1), "1 brano");
        assert_eq!(trn!("{n} track", "{n} tracks", 4), "4 brani");
        set_language("en");
        assert_eq!(tr("Settings"), "Settings");
        assert_eq!(trn!("{n} track", "{n} tracks", 4), "4 tracks");
    }

    #[test]
    fn resolves_settings() {
        assert_eq!(resolve("it"), "it");
        assert_eq!(resolve("it_IT.UTF-8"), "it");
        assert_eq!(resolve("en"), "en");
    }
}
